// Единственное место, где тесты решают, КАКОЙ bash исполняет .sh-реализации.
//
// Зачем отдельная переменная вместо голого 'bash': основная целевая ОС
// проекта — macOS с системным /bin/bash 3.2, но на macOS-раннере GitHub в
// PATH первым стоит Homebrew-bash 5.x. Голый 'bash' проверял бы там совсем
// не ту реализацию и давал бы зелёный тик, не доказывающий ничего про 3.2, —
// ловушка ровно той же формы, что уже сработала на Windows, где 'bash' из
// системного PATH разрешался в WSL вместо Git Bash. Поэтому macOS-нога CI
// выставляет OAB_BASH=/bin/bash явно.
//
// Тихого отката на PATH-bash при неверном OAB_BASH здесь нет намеренно: если
// указанный бинарник не запускается, тесты обязаны упасть, а не незаметно
// проверить что-то другое.
export const BASH = process.env.OAB_BASH || 'bash';
